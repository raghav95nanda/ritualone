import assert from 'node:assert/strict';
import ts from 'typescript';
import {readFileSync,existsSync} from 'node:fs';
const source=readFileSync('src/lib/community.ts','utf8').replace("'./rituals'",JSON.stringify(new URL('../src/lib/rituals.ts',import.meta.url).href));
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {weekStart,communityWeek,sampleEvents,eventCalendar,samplePosts}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
assert.equal(weekStart('2026-10-11'),'2026-10-05');
assert.equal(weekStart('2026-10-12'),'2026-10-12');
assert.equal(weekStart('2027-01-01'),'2026-12-28');
assert.equal(communityWeek(new Date('2026-10-11T18:29:59Z')),'2026-10-05');
assert.equal(communityWeek(new Date('2026-10-11T18:30:00Z')),'2026-10-12');
const events=sampleEvents(new Date('2026-10-11T10:00:00Z'));
assert.equal(events.length,3);
assert.deepEqual(events.map(e=>e.title),['Book Club meeting','5k Morning Fun Run','Meditation in the park']);
assert.deepEqual(events.map(e=>e.day),['2026-10-17','2026-10-18','2026-10-18']);
assert.equal(sampleEvents(new Date('2026-10-17T15:00:00Z'))[0].day,'2026-10-24');
const calendar=eventCalendar(events[1],new Date('2026-10-11T10:00:00Z'));
assert(calendar.includes('DTSTART:20261018T010000Z'));
assert(calendar.includes('DTEND:20261018T020000Z'));
assert(calendar.includes('SUMMARY:[SAMPLE] 5k Morning Fun Run'));
assert(calendar.endsWith('END:VCALENDAR\r\n'));
assert.equal((calendar.match(/BEGIN:VEVENT/g)||[]).length,1);
assert.equal((eventCalendar({...events[1],title:'Test\nBEGIN:VEVENT,escape;test'}).match(/\r\nBEGIN:VEVENT/g)||[]).length,1);
assert.equal(samplePosts().length,3);
for(const sound of ['rain','forest'])assert(existsSync('public/sounds/'+sound+'.mp3'));
console.log('Weekly IST rollover, year boundary, sample events, calendar times and escaping checks passed.');
